function analyzeCodeStructure(content: string, extension: string): string {
  const lines = content.split('\n');
  const nonEmptyLines = lines.filter(line => line.trim().length > 0);
  const commentLines = lines.filter(line => isComment(line, extension));
  const codeLines = nonEmptyLines.filter(line => !isComment(line, extension));
  
  let analysis = '';
  
  if (lines.length > 100) {
    analysis += 'This is a substantial file with over 100 lines of code. ';
  } else if (lines.length > 50) {
    analysis += 'This is a medium-sized file with 50-100 lines of code. ';
  } else {
    analysis += 'This is a relatively small file with less than 50 lines of code. ';
  }
  
  const commentRatio = commentLines.length / nonEmptyLines.length;
  if (commentRatio > 0.3) {
    analysis += 'The file is well-documented with extensive comments. ';
  } else if (commentRatio > 0.1) {
    analysis += 'The file has moderate documentation. ';
  } else {
    analysis += 'The file has minimal comments. ';
  }
  
  // Language-specific analysis
  if (extension === '.js' || extension === '.ts') {
    if (content.includes('function ') || content.includes('const ') || content.includes('let ')) {
      analysis += 'Contains function definitions and variable declarations. ';
    }
    if (content.includes('import ') || content.includes('require(')) {
      analysis += 'Uses module imports. ';
    }
  } else if (extension === '.py') {
    if (content.includes('def ')) {
      analysis += 'Contains function definitions. ';
    }
    if (content.includes('class ')) {
      analysis += 'Contains class definitions. ';
    }
    if (content.includes('import ') || content.includes('from ')) {
      analysis += 'Uses module imports. ';
    }
  } else if (extension === '.java') {
    if (content.includes('class ')) {
      analysis += 'Contains class definitions. ';
    }
    if (content.includes('public ') || content.includes('private ')) {
      analysis += 'Uses access modifiers. ';
    }
  }
  
  return analysis.trim();
}

function countComments(content: string, extension: string): number {
  return content.split('\n').filter(line => isComment(line, extension)).length;
}

function isComment(line: string, extension: string): boolean {
  const trimmed = line.trim();
  
  // Single-line comments
  if (extension === '.py' || extension === '.sh' || extension === '.bash') {
    return trimmed.startsWith('#');
  } else if (['.js', '.ts', '.jsx', '.tsx', '.java', '.cpp', '.c', '.cs', '.go', '.php'].includes(extension)) {
    return trimmed.startsWith('//') || (trimmed.startsWith('/*') && trimmed.endsWith('*/'));
  } else if (extension === '.html' || extension === '.xml') {
    return trimmed.startsWith('<!--') && trimmed.endsWith('-->');
  } else if (extension === '.css' || extension === '.scss') {
    return trimmed.startsWith('/*') && trimmed.endsWith('*/');
  }
  
  return false;
}

export function downloadFile(content: string, filename: string): void {
  const blob = new Blob([content], { type: 'text/markdown' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}